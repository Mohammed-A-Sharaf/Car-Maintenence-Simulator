/* Virtual Garage - the workshop backdrop.
   window.VG_GARAGE is a flat list of shapes in world units (generated by
   tools/make_garage.py). This turns it into one SVG group, once, so the whole
   backdrop lives in the same coordinate space as the car: it pans, zooms and
   focuses with the camera instead of being a flat picture behind it. */
(function () {
  "use strict";
  var VG = window.VG, U = VG.util;
  var el = U.el;
  var seq = 0;

  function isPair(f) { return Object.prototype.toString.call(f) === "[object Array]"; }

  /* vertical linear gradient between two colours, in user space */
  function gradient(defs, fill, x, y, w, h) {
    var id = "gg" + (++seq);
    var g = el("linearGradient", {
      id: id, gradientUnits: "userSpaceOnUse",
      x1: x, y1: y, x2: x, y2: y + (h || 1)
    });
    g.appendChild(el("stop", { offset: 0, "stop-color": fill[0] }));
    g.appendChild(el("stop", { offset: 1, "stop-color": fill[1] }));
    defs.appendChild(g);
    return "url(#" + id + ")";
  }

  /* radial gradient, used for the light pools on the floor */
  function radial(defs, fill, cx, cy, r) {
    var id = "gr" + (++seq);
    var g = el("radialGradient", {
      id: id, gradientUnits: "userSpaceOnUse", cx: cx, cy: cy, r: r || 1
    });
    g.appendChild(el("stop", { offset: 0, "stop-color": fill[0] }));
    g.appendChild(el("stop", { offset: 1, "stop-color": fill[1] }));
    defs.appendChild(g);
    return "url(#" + id + ")";
  }

  /* box shapes fade top-to-bottom (light falls, walls shade); ellipses glow
     from the middle, which is how a pool of light on the floor behaves */
  function paint(defs, fill, box, round) {
    if (!isPair(fill)) return fill;
    if (round) {
      var r = Math.max(box[2], box[3]) / 2;
      return radial(defs, fill, box[0] + box[2] / 2, box[1] + box[3] / 2, r);
    }
    return gradient(defs, fill, box[0], box[1], box[2], box[3]);
  }

  function build(defs) {
    var g = el("g", { "class": "layer-garage" });
    var list = window.VG_GARAGE || [];
    for (var i = 0; i < list.length; i++) {
      var s = list[i], node;
      if (s.k === "rect") {
        node = el("rect", {
          x: s.x, y: s.y, width: s.w, height: s.h,
          rx: s.r || 0,
          fill: paint(defs, s.fill, [s.x, s.y, s.w, s.h]),
          opacity: s.o == null ? 1 : s.o
        });
      } else if (s.k === "ell") {
        node = el("ellipse", {
          cx: s.cx, cy: s.cy, rx: s.rx, ry: s.ry,
          fill: paint(defs, s.fill, [s.cx - s.rx, s.cy - s.ry, s.rx * 2, s.ry * 2], true),
          opacity: s.o == null ? 1 : s.o
        });
      } else if (s.k === "poly") {
        var pts = [], minY = Infinity, maxY = -Infinity;
        for (var p = 0; p < s.pts.length; p++) {
          pts.push(s.pts[p][0] + "," + s.pts[p][1]);
          if (s.pts[p][1] < minY) minY = s.pts[p][1];
          if (s.pts[p][1] > maxY) maxY = s.pts[p][1];
        }
        var box = [s.pts[0][0], minY, s.pts[1][0] - s.pts[0][0], maxY - minY];
        node = el("polygon", {
          points: pts.join(" "),
          fill: paint(defs, s.fill, box),
          opacity: s.o == null ? 1 : s.o
        });
      } else if (s.k === "line") {
        node = el("line", {
          x1: s.x1, y1: s.y1, x2: s.x2, y2: s.y2,
          stroke: s.c, "stroke-width": s.w, "stroke-linecap": "round",
          opacity: s.o == null ? 1 : s.o
        });
      }
      if (node) {
        if (s.tag === "led") { n.leds = n.leds || []; n.leds.push(node); }
        g.appendChild(node);
      }
    }
    return g;
  }

  /* the pools of light on the wall behind the car, gently breathing so the
     workshop does not look like a still photograph */
  function animate(t) {
    var leds = n.leds || [];
    if (!leds.length) return;
    var k = 0.5 + 0.5 * Math.sin(t * 0.6);
    var o = (0.86 + 0.08 * k).toFixed(3);
    for (var i = 0; i < leds.length; i++) leds[i].setAttribute("opacity", o);
  }

  var n = {};
  VG.garage = { build: build, animate: animate, nodes: n };
})();
